# 搜尋詞全都撈不到東西時的保底
NEWS_FALLBACK_QUERY = "台灣 生活"


def _pick(pool, day, offset=0):
    return pool[(day.toordinal() + offset) % len(pool)]


def trivia_topic(day, offset=0):
    """當天的小知識主題。offset 用於換一個主題重試。"""
    return _pick(TRIVIA_TOPICS, day, offset)


def joke_topic(day, offset=0):
    """當天的笑話主題。offset 用於換一個主題重試。"""
    return _pick(JOKE_TOPICS, day, offset)


def news_query(day, offset=0):
    """當天的新鮮事搜尋詞。offset 用於換一組搜尋詞重試。"""
    return _pick(NEWS_QUERIES, day, offset)
