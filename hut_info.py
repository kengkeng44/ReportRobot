def place(site):
    return PLACE.get(site, site)


def display(slot):
    """周圍營地這種各站都有的名字前面加地點。"""
    if slot.unit.startswith("周圍"):
        return f"{place(slot.site)} {slot.unit}"
    return slot.unit


def transport_card(place_name):
    t = TRANSPORT.get(place_name)
    if not t:
        return ""
    body = t["text"]
    if t.get("from_home"):
        body += f"\n從中和出發：\n{t['from_home']}"
    if t["checked"]:
        return f"{place_name}：{body}（{t['checked']} 核對）"
    return f"{place_name}：{body}\n⚠️ 尚未核對官方資料，出發前請查：{t['source']}"


def apply_phrase(slot):
    return f"用 hut-apply 申請 {display(slot)} {slot.day.isoformat()} 2人"
